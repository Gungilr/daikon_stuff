#!/usr/bin/env python3
"""Generate a fuzz target bundling NIST Juliet C 1.3 test cases.

    python3 scripts/bench/make_juliet.py JULIET/C

Juliet (NIST SARD, public domain) has one file per flaw, each with a bad()
function. These are the "_fgets_" variants, where the flawed value is read
from stdin, so the fuzz input controls whether the flaw fires. Every case's
bad() goes into one target: the first input byte picks the case, the rest is
its stdin. Each flaw line gets a FUZZ_BUG marker with the exact condition
under which it misbehaves, so the scorer has ground truth independent of any
sanitizer.

Output: fuzz/targets/juliet/juliet.c (+ cases/, support/), juliet.seeds.
"""
import os
import re
import shutil
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, "fuzz", "targets", "juliet")

# (id, kind, file under testcases/, sink text in bad(), condition, fatal, seed)
CASES = [
    ("j190_add", "UB", "CWE190_Integer_Overflow/s02/CWE190_Integer_Overflow__int_fgets_add_01.c",
     "int result = data + 1;", "data == INT_MAX", False, "5"),
    ("j190_mul", "UB", "CWE190_Integer_Overflow/s03/CWE190_Integer_Overflow__int_fgets_multiply_01.c",
     "int result = data * 2;", "data > INT_MAX / 2", False, "7"),
    ("j191_sub", "UB", "CWE191_Integer_Underflow/s02/CWE191_Integer_Underflow__int_fgets_sub_01.c",
     "int result = data - 1;", "data == INT_MIN", False, "9"),
    ("j369_div", "UB", "CWE369_Divide_by_Zero/s01/CWE369_Divide_by_Zero__int_fgets_divide_01.c",
     "printIntLine(100 / data);", "data == 0", False, "4"),
    ("j369_mod", "UB", "CWE369_Divide_by_Zero/s01/CWE369_Divide_by_Zero__int_fgets_modulo_01.c",
     "printIntLine(100 % data);", "data == 0", False, "3"),
    ("j121_stack", "memory", "CWE121_Stack_Based_Buffer_Overflow/s01/CWE121_Stack_Based_Buffer_Overflow__CWE129_fgets_01.c",
     "buffer[data] = 1;", "data >= 10", True, "2"),
    ("j122_heap", "memory", "CWE122_Heap_Based_Buffer_Overflow/s06/CWE122_Heap_Based_Buffer_Overflow__c_CWE129_fgets_01.c",
     "buffer[data] = 1;", "data >= 10", True, "6"),
    ("j124_underwrite", "memory", "CWE124_Buffer_Underwrite/s01/CWE124_Buffer_Underwrite__CWE839_fgets_01.c",
     "buffer[data] = 1;", "data < 0", True, "1"),
    ("j126_overread", "memory", "CWE126_Buffer_Overread/s01/CWE126_Buffer_Overread__CWE129_fgets_01.c",
     "printIntLine(buffer[data]);", "data >= 10", True, "8"),
    ("j127_underread", "memory", "CWE127_Buffer_Underread/s01/CWE127_Buffer_Underread__CWE839_fgets_01.c",
     "printIntLine(buffer[data]);", "data < 0", True, "0"),
    ("j194_signext", "memory", "CWE194_Unexpected_Sign_Extension/s01/CWE194_Unexpected_Sign_Extension__fgets_memcpy_01.c",
     "memcpy(dest, source, data);", "data < 0", True, "50"),
    ("j195_signconv", "memory", "CWE195_Signed_to_Unsigned_Conversion_Error/s01/CWE195_Signed_to_Unsigned_Conversion_Error__fgets_malloc_01.c",
     "char * dataBuffer = (char *)malloc(data);", "data <= 0", True, "50"),
    ("j197_char", "logic", "CWE197_Numeric_Truncation_Error/s01/CWE197_Numeric_Truncation_Error__int_fgets_to_char_01.c",
     "char charData = (char)data;", "data < CHAR_MIN || data > CHAR_MAX", False, "65"),
    ("j197_short", "logic", "CWE197_Numeric_Truncation_Error/s01/CWE197_Numeric_Truncation_Error__int_fgets_to_short_01.c",
     "short shortData = (short)data;", "data < SHRT_MIN || data > SHRT_MAX", False, "1000"),
]


def main(argv=None):
    argv = argv if argv is not None else sys.argv[1:]
    if len(argv) != 1:
        print(__doc__)
        return 2
    jroot = argv[0]
    os.makedirs(os.path.join(OUT, "cases"), exist_ok=True)
    os.makedirs(os.path.join(OUT, "support"), exist_ok=True)
    for f in ("io.c", "std_testcase.h", "std_testcase_io.h", "std_thread.h"):
        shutil.copy(os.path.join(jroot, "testcasesupport", f), os.path.join(OUT, "support", f))

    includes, fns, seeds = [], [], []
    header = ["/* Generated by scripts/bench/make_juliet.py from NIST Juliet C 1.3",
              " * (public domain). Byte 0 picks a case; the rest is its stdin.",
              " * Planted bugs (benchmark ground truth, see scripts/bench):"]
    for k, (bid, kind, rel, sink, cond, fatal, seed) in enumerate(CASES):
        text = open(os.path.join(jroot, "testcases", rel), errors="replace").read()
        bad = text.index("_bad()\n{")
        at = text.index(sink, bad)
        line_start = text.rfind("\n", 0, at) + 1
        indent = text[line_start:at]
        macro = "FUZZ_BUG_FATAL" if fatal else "FUZZ_BUG"
        text = (text[:line_start] + '%s%s("%s", %s);\n' % (indent, macro, bid, cond)
                + text[line_start:])
        # Each case includes the support header by relative path.
        text = text.replace('#include "std_testcase.h"', '#include "../support/std_testcase.h"')
        name = os.path.basename(rel)
        with open(os.path.join(OUT, "cases", name), "w") as f:
            f.write(text)
        fn = re.search(r"void (\w+_bad)\(\)", text).group(1)
        includes.append('#undef CHAR_ARRAY_SIZE\n#include "cases/%s"' % name)
        fns.append(fn)
        header.append(" *   %-16s (%s)  case %d: %s" % (bid, kind, k, rel.split("/")[0]))
        seeds.append((bytes([k]) + seed.encode() + b"\n").hex())
    header.append(" */")
    body = "\n".join(header) + r'''
#define OMITGOOD
#include "../../runtime/prog_shim.h"
#include "support/io.c"
''' + "\n".join(includes) + r'''

/* `()` not `(void)`: Juliet declares bad() unprototyped, and UBSan's
 * -fsanitize=function flags a call through a mismatched pointer type. */
static void (*const juliet_cases[])() = {
''' + ",\n".join("    " + f for f in fns) + r'''
};
#define JULIET_N ((int)(sizeof juliet_cases / sizeof juliet_cases[0]))

/* run_prog() passes argc through: use it as the case number. */
static int juliet_run(int which, char **argv) {
    (void)argv;
    juliet_cases[which]();
    return 0;
}

void fuzz_target(const uint8_t *data, size_t size) {
    if (size == 0)
        return;
    char *argv[] = {"juliet", NULL};
    run_prog((int (*)())juliet_run, data[0] % JULIET_N, argv, data + 1, size - 1);
}
'''
    with open(os.path.join(OUT, "juliet.c"), "w") as f:
        f.write(body)
    with open(os.path.join(OUT, "juliet.seeds"), "w") as f:
        f.write("# generated by scripts/bench/make_juliet.py: one benign input per case\n")
        f.write("\n".join(seeds) + "\n")
    print("wrote", os.path.join(OUT, "juliet.c"), "with", len(CASES), "cases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
