#!/usr/bin/env python3
"""Generate a single-file fuzz target from Magma's libpng (7 real bugs).

    python3 scripts/bench/make_libpng.py MAGMA_DIR LIBPNG_CHECKOUT

LIBPNG_CHECKOUT is libpng at Magma's commit a37d483 with Magma's
targets/libpng/patches/bugs/*.patch applied (%MAGMA_BUG% -> PNG00x). The
sources are copied to fuzz/targets/libpng/src/ (gitignored), and
fuzz/targets/libpng/libpng.c includes them all (a unity build), so every
build the loop and the benchmark make (Kvasir, coverage, sanitizer, AFL++,
oracle) stays a single-file compile.

Magma's canaries become ground truth exactly as FUZZ_BUG does:
MAGMA_LOG(bug, cond) prints `@@BUG <bug>` in the oracle build only.
"""
import os
import shutil
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, "fuzz", "targets", "libpng")
SOURCES = ["png.c", "pngerror.c", "pngget.c", "pngmem.c", "pngpread.c", "pngread.c",
           "pngrio.c", "pngrtran.c", "pngrutil.c", "pngset.c", "pngtrans.c",
           # png.c refers to the write side too
           "pngwio.c", "pngwrite.c", "pngwtran.c", "pngwutil.c"]
# Bug classes from the canary conditions in Magma's patches.
KINDS = {"PNG001": "UB", "PNG002": "logic", "PNG003": "memory", "PNG004": "UB",
         "PNG005": "memory", "PNG006": "memory", "PNG007": "memory"}

ADAPTER = r'''
/* Magma canaries, in the oracle build only (scripts/bench). */
#ifdef FUZZ_ORACLE
#include <stdio.h>
#define MAGMA_ENABLE_CANARIES
#define MAGMA_AND(a, b) ((a) && (b))
#define MAGMA_LOG(b, c) \
    do { if (c) fprintf(stderr, "@@BUG %s %s\n", (b), __func__); } while (0)
#endif

#include "../../runtime/fuzz.h"
''' + "".join('#include "src/%s"\n' % s for s in SOURCES) + r'''
#include <stdlib.h>
#include <string.h>

/* A C port of libpng's contrib/oss-fuzz/libpng_read_fuzzer.cc, the harness
 * Magma uses for this target. */
#define PNG_HEADER 8

typedef struct {
    const uint8_t *data;
    size_t left;
} fuzz_buf;

static void fuzz_png_read(png_structp png, png_bytep out, size_t n) {
    fuzz_buf *b = (fuzz_buf *)png_get_io_ptr(png);
    if (b->left < n)
        png_error(png, "read error");
    memcpy(out, b->data, n);
    b->data += n;
    b->left -= n;
}

static png_voidp fuzz_png_malloc(png_structp png, png_alloc_size_t n) {
    (void)png;
    return n > 8000000 ? NULL : malloc(n);   /* avoid OOM, as upstream does */
}

static void fuzz_png_free(png_structp png, png_voidp p) {
    (void)png;
    free(p);
}

void fuzz_target(const uint8_t *data, size_t size) {
    if (size < PNG_HEADER || png_sig_cmp(data, 0, PNG_HEADER))
        return;
    png_structp png = png_create_read_struct(PNG_LIBPNG_VER_STRING, NULL, NULL, NULL);
    if (!png)
        return;
    png_infop info = png_create_info_struct(png);
    png_infop end_info = png_create_info_struct(png);
    png_voidp row = NULL;
    fuzz_buf buf = {data + PNG_HEADER, size - PNG_HEADER};
    if (!info || !end_info)
        goto done;
    png_set_mem_fn(png, NULL, fuzz_png_malloc, fuzz_png_free);
    png_set_crc_action(png, PNG_CRC_QUIET_USE, PNG_CRC_QUIET_USE);
#ifdef PNG_IGNORE_ADLER32
    png_set_option(png, PNG_IGNORE_ADLER32, PNG_OPTION_ON);
#endif
    png_set_read_fn(png, &buf, fuzz_png_read);
    png_set_sig_bytes(png, PNG_HEADER);
    if (setjmp(png_jmpbuf(png)))
        goto done;
    png_read_info(png, info);
    png_uint_32 width, height;
    int bit_depth, color_type, interlace, compression, filter;
    if (!png_get_IHDR(png, info, &width, &height, &bit_depth, &color_type,
                      &interlace, &compression, &filter))
        goto done;
    if (width && height > 100000000 / width)
        goto done;
    png_set_gray_to_rgb(png);
    png_set_expand(png);
    png_set_packing(png);
    png_set_scale_16(png);
    png_set_tRNS_to_alpha(png);
    int passes = png_set_interlace_handling(png);
    png_read_update_info(png, info);
    row = png_malloc(png, png_get_rowbytes(png, info));
    for (int p = 0; p < passes; ++p)
        for (png_uint_32 y = 0; y < height; ++y)
            png_read_row(png, (png_bytep)row, NULL);
    png_read_end(png, end_info);
done:
    if (row)
        png_free(png, row);
    png_destroy_read_struct(&png, info ? &info : NULL, end_info ? &end_info : NULL);
}
'''


def main(argv=None):
    argv = argv if argv is not None else sys.argv[1:]
    if len(argv) != 2:
        print(__doc__)
        return 2
    magma, checkout = argv
    src = os.path.join(OUT, "src")
    os.makedirs(src, exist_ok=True)
    for f in SOURCES + ["png.h", "pngconf.h", "pngdebug.h", "pnginfo.h", "pngpriv.h",
                        "pngstruct.h"]:
        shutil.copy(os.path.join(checkout, f), os.path.join(src, f))
    shutil.copy(os.path.join(checkout, "scripts", "pnglibconf.h.prebuilt"),
                os.path.join(src, "pnglibconf.h"))
    header = ["/* Generated by scripts/bench/make_libpng.py: libpng at Magma's commit",
              " * with Magma's 7 bug patches, as one translation unit.",
              " * Planted bugs (benchmark ground truth, see scripts/bench):"]
    header += [" *   %-8s (%s)" % (b, k) for b, k in sorted(KINDS.items())]
    header.append(" */")
    with open(os.path.join(OUT, "libpng.c"), "w") as f:
        # The canary macro names the planted ids for the scorer's parser.
        f.write("\n".join(header) + "\n")
        f.write("/* " + " ".join('FUZZ_BUG("%s", 0)' % b for b in sorted(KINDS)) + " */\n")
        f.write(ADAPTER)
    corpus = os.path.join(magma, "targets", "libpng", "corpus", "libpng_read_fuzzer")
    lines = ["# Magma's libpng corpus (" + ", ".join(sorted(os.listdir(corpus))) + ")"]
    for name in sorted(os.listdir(corpus)):
        lines.append(open(os.path.join(corpus, name), "rb").read().hex())
    with open(os.path.join(OUT, "libpng.seeds"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.join(OUT, "libpng.c"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
